/// The windowing system underneath.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DisplayServer {
    /// macOS.
    Quartz,
    /// Windows.
    Windows,
    /// X11, including XWayland used as an X server by an X11 session.
    X11,
    /// A Wayland session.
    Wayland,
    /// Nothing detected — headless, CI, or a bare TTY.
    Headless,
}

/// The Wayland compositor, where one is running.
///
/// The distinction that matters is not cosmetic: the wlroots family implements
/// no `GlobalShortcuts` portal at all, so for those the only hotkey path is a
/// compositor keybinding invoking the CLI.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Compositor {
    /// sway — wlroots, no global shortcut portal.
    Sway,
    /// Hyprland — wlroots, no global shortcut portal.
    Hyprland,
    /// river — wlroots, no global shortcut portal.
    River,
    /// niri — no global shortcut portal.
    Niri,
    /// Wayfire — wlroots, no global shortcut portal.
    Wayfire,
    /// GNOME/Mutter — implements the portal.
    Gnome,
    /// KDE/KWin — implements the portal.
    Kde,
    /// Not a Wayland session, or a compositor Scrozz does not recognise.
    Other,
}

impl Compositor {
    /// Whether this compositor implements the `GlobalShortcuts` portal.
    ///
    /// `false` for the wlroots family. This is the fact D11 is built on.
    #[must_use]
    pub const fn has_global_shortcut_portal(self) -> bool {
        matches!(self, Self::Gnome | Self::Kde)
    }

    /// The config file the user would edit, for display alongside the line.
    #[must_use]
    pub const fn config_path(self) -> Option<&'static str> {
        match self {
            Self::Sway => Some("~/.config/sway/config"),
            Self::Hyprland => Some("~/.config/hypr/hyprland.conf"),
            Self::River => Some("~/.config/river/init"),
            Self::Niri => Some("~/.config/niri/config.kdl"),
            _ => None,
        }
    }

    /// The exact config line binding `accelerator` to `command`.
    ///
    /// This is the whole remedy on wlroots, so it is generated rather than
    /// described: onboarding shows it and the user pastes it. `None` when the
    /// compositor has no known config syntax, or when the key has no keysym
    /// spelling to put in the file.
    #[must_use]
    pub fn binding_for(self, accelerator: &Accelerator, command: &str) -> Option<String> {
        let key = accelerator.keysym()?;
        let mods = accelerator.mods;

        let line = match self {
            Self::Sway => {
                let mut parts = Vec::new();
                if mods.contains(Modifiers::CONTROL) {
                    parts.push("Ctrl");
                }
                if mods.contains(Modifiers::ALT) {
                    parts.push("Mod1");
                }
                if mods.contains(Modifiers::SHIFT) {
                    parts.push("Shift");
                }
                if mods.contains(Modifiers::SUPER) {
                    parts.push("Mod4");
                }
                parts.push(key);
                format!("bindsym {} exec {command}", parts.join("+"))
            }
            Self::Hyprland => {
                let mut parts = Vec::new();
                if mods.contains(Modifiers::CONTROL) {
                    parts.push("CTRL");
                }
                if mods.contains(Modifiers::ALT) {
                    parts.push("ALT");
                }
                if mods.contains(Modifiers::SHIFT) {
                    parts.push("SHIFT");
                }
                if mods.contains(Modifiers::SUPER) {
                    parts.push("SUPER");
                }
                format!("bind = {}, {key}, exec, {command}", parts.join("_"))
            }
            Self::River => {
                let mut parts = Vec::new();
                if mods.contains(Modifiers::CONTROL) {
                    parts.push("Control");
                }
                if mods.contains(Modifiers::ALT) {
                    parts.push("Mod1");
                }
                if mods.contains(Modifiers::SHIFT) {
                    parts.push("Shift");
                }
                if mods.contains(Modifiers::SUPER) {
                    parts.push("Super");
                }
                if parts.is_empty() {
                    parts.push("None");
                }
                format!(
                    "riverctl map normal {} {key} spawn '{command}'",
                    parts.join("+")
                )
            }
            Self::Niri => {
                let mut parts = Vec::new();
                if mods.contains(Modifiers::CONTROL) {
                    parts.push("Ctrl");
                }
                if mods.contains(Modifiers::ALT) {
                    parts.push("Alt");
                }
                if mods.contains(Modifiers::SHIFT) {
                    parts.push("Shift");
                }
                if mods.contains(Modifiers::SUPER) {
                    parts.push("Mod");
                }
                parts.push(key);
                format!("{} {{ spawn-sh \"{command}\"; }}", parts.join("+"))
            }
            Self::Wayfire | Self::Gnome | Self::Kde | Self::Other => return None,
        };

        Some(line)
    }
}

/// What the environment allows, decided once at construction.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Session {
    /// The windowing system.
    pub server: DisplayServer,
    /// The compositor, on Wayland.
    pub compositor: Compositor,
    /// The raw `XDG_CURRENT_DESKTOP`, kept for diagnostics.
    pub desktop: String,
}

impl Session {
    /// Reads the current environment.
    #[must_use]
    pub fn detect() -> Self {
        let desktop = std::env::var("XDG_CURRENT_DESKTOP").unwrap_or_default();

        if cfg!(target_os = "macos") {
            return Self {
                server: DisplayServer::Quartz,
                compositor: Compositor::Other,
                desktop,
            };
        }
        if cfg!(target_os = "windows") {
            return Self {
                server: DisplayServer::Windows,
                compositor: Compositor::Other,
                desktop,
            };
        }

        Self::from_env(
            Some(desktop.as_str()),
            std::env::var("WAYLAND_DISPLAY").ok().as_deref(),
            std::env::var("XDG_SESSION_TYPE").ok().as_deref(),
            std::env::var("DISPLAY").ok().as_deref(),
        )
    }

    /// Classifies a Unix session from explicit environment values.
    ///
    /// Deliberately free of `cfg!(target_os)` and of any read of the real
    /// environment, so every branch — including every Wayland compositor — is
    /// reachable from a test on any platform. A version that read the process
    /// environment could only be tested by mutating it, which no parallel test
    /// suite can do safely.
    #[must_use]
    pub fn from_env(
        xdg_current_desktop: Option<&str>,
        wayland_display: Option<&str>,
        xdg_session_type: Option<&str>,
        x11_display: Option<&str>,
    ) -> Self {
        let desktop = xdg_current_desktop.unwrap_or_default().to_owned();

        let on_wayland = wayland_display.is_some_and(|it| !it.is_empty())
            || xdg_session_type.is_some_and(|it| it.eq_ignore_ascii_case("wayland"));

        // XDG_CURRENT_DESKTOP is colon-separated and may be "sway" or
        // "Hyprland" or "GNOME:GNOME-Classic".
        let compositor = desktop
            .split(':')
            .find_map(|part| match part.trim().to_ascii_lowercase().as_str() {
                "sway" => Some(Compositor::Sway),
                "hyprland" => Some(Compositor::Hyprland),
                "river" => Some(Compositor::River),
                "niri" => Some(Compositor::Niri),
                "wayfire" => Some(Compositor::Wayfire),
                "gnome" | "gnome-classic" | "ubuntu" | "pop" => Some(Compositor::Gnome),
                "kde" | "plasma" => Some(Compositor::Kde),
                _ => None,
            })
            .unwrap_or(Compositor::Other);

        let server = if on_wayland {
            DisplayServer::Wayland
        } else if xdg_session_type.is_some_and(|it| it.eq_ignore_ascii_case("x11"))
            || x11_display.is_some_and(|it| !it.is_empty())
        {
            DisplayServer::X11
        } else {
            DisplayServer::Headless
        };

        Self {
            server,
            compositor,
            desktop,
        }
    }

    /// Whether global hotkeys can be registered at all here.
    #[must_use]
    pub const fn supports_global_hotkeys(&self) -> bool {
        !matches!(self.server, DisplayServer::Wayland)
    }

    /// The `Unsupported` error this session produces, with its remedy.
    ///
    /// Split out and public because onboarding renders exactly this text
    /// (decision D26 item 4) rather than inventing its own wording.
    #[must_use]
    pub fn unsupported(&self, accelerator: &Accelerator, command: &str) -> Error {
        let why = if self.compositor.has_global_shortcut_portal() {
            format!(
                "{desktop} on Wayland implements the GlobalShortcuts portal, but Scrozz does \
                 not speak it yet, and an X11 grab under XWayland never sees Wayland \
                 keystrokes — a binding here would look registered and never fire. Bind \
                 {accelerator} to `{command}` in your desktop's keyboard settings instead.",
                desktop = if self.desktop.is_empty() {
                    "this desktop"
                } else {
                    &self.desktop
                },
            )
        } else if let Some(line) = self.compositor.binding_for(accelerator, command) {
            let path = self
                .compositor
                .config_path()
                .unwrap_or("your compositor config");
            format!(
                "wlroots compositors implement no global shortcut portal, so no application \
                 can register a system-wide hotkey. Bind it in the compositor instead — add \
                 this to {path}:\n\n    {line}\n\nthen reload the config."
            )
        } else {
            format!(
                "this Wayland compositor implements no global shortcut portal, so no \
                 application can register a system-wide hotkey. Bind a compositor keybinding \
                 to `{command}` instead."
            )
        };

        Error::Unsupported {
            what: format!("global hotkey {accelerator}"),
            why,
        }
    }
}

