fn parse_code(token: &str) -> Option<Code> {
    let upper = token.to_ascii_uppercase();
    KEYS.iter()
        .find(|(code, display, _)| {
            display.eq_ignore_ascii_case(token)
                // Accept the DOM spellings too, so a config file written as
                // `Digit4` or `KeyA` round-trips.
                || format!("{code}").eq_ignore_ascii_case(&upper)
        })
        .map(|(code, _, _)| *code)
}

fn display_for(code: Code) -> String {
    KEYS.iter()
        .find(|(candidate, _, _)| *candidate == code)
        .map_or_else(
            || format!("{code}"),
            |(_, display, _)| (*display).to_owned(),
        )
}

fn keysym_for(code: Code) -> Option<&'static str> {
    KEYS.iter()
        .find(|(candidate, _, _)| *candidate == code)
        .map(|(_, _, keysym)| *keysym)
}

