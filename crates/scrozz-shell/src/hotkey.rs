//! Global hotkeys, and the honest account of where they do not exist.
//!
//! A hotkey that silently does nothing is the worst failure this class of app
//! has: the user presses the key, no capture appears, and there is nothing on
//! screen to explain why. Everything in this module exists to make that outcome
//! impossible — either the binding works, or the caller gets an error carrying
//! the remedy in words the user can act on.
//!
//! Three things can go wrong, and each is a distinct, reported outcome rather
//! than a silent no-op:
//!
//! 1. **The combination is already Scrozz's.** Caught in [`GlobalHotkeys`]'s own
//!    bookkeeping before the OS is touched.
//! 2. **The combination belongs to the OS.** `Cmd+Shift+4` is macOS's own
//!    screenshot shortcut, and — this is the trap — Carbon's
//!    `RegisterEventHotKey` returns success for it anyway. The system keeps the
//!    key and Scrozz's handler never fires. No API reports this, so
//!    [`reserved_shortcuts`] is a table of the combinations known to be taken,
//!    checked before registering.
//! 3. **The platform has no global hotkeys at all.** See below.
//!
//! # Wayland (decision D11)
//!
//! On wlroots compositors — sway, Hyprland, river — there is **no
//! `GlobalShortcuts` portal**, and a Wayland client cannot grab keys. There is
//! no implementation to write: the only path that exists is the user binding a
//! compositor keybinding to the `scrozz` CLI. That is why the CLI is a platform
//! requirement rather than a convenience.
//!
//! [`register`](HotkeyManager::register) therefore returns
//! [`Error::Unsupported`] there, and its `why` carries the exact config line to
//! paste, generated by [`Compositor::binding_for`]. Onboarding shows it. A user
//! who is not told this concludes the app is broken.
//!
//! GNOME and KDE on Wayland *do* implement the portal, but the `global-hotkey`
//! crate this module builds on is X11-only, and an X11 grab under XWayland does
//! not see native Wayland keystrokes. Rather than register a binding that
//! appears to work and never fires, those sessions also report `Unsupported`,
//! with a `why` that says the portal exists and is not yet wired up.

