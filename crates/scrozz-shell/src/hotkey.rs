/// A parsed, platform-normalised key combination.
///
/// Accelerators are written platform-independently — `"Cmd+Shift+4"` — and
/// normalised on parse. `Cmd`, `Command`, `Super` and `Meta` are interchangeable
/// spellings of the *primary* modifier, which is Command on macOS and **Control
/// on Windows and Linux**, because `Super` on those platforms is the desktop
/// environment's key and binding it fights the window manager.
///
/// The physical Super/Windows key is still reachable, spelled `Win` or `Logo`,
/// for the rare binding that genuinely wants it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Accelerator {
    mods: Modifiers,
    code: Code,
}

impl Accelerator {
    /// Parses a platform-independent accelerator string.
    ///
    /// Modifiers may appear in any order and the key may appear anywhere, so
    /// long as there is exactly one non-modifier token. Matching is
    /// case-insensitive and whitespace around `+` is ignored.
    ///
    /// # Errors
    ///
    /// Returns [`Error::InvalidRequest`] if a token is empty, unrecognised, or
    /// if the string does not name exactly one non-modifier key.
    pub fn parse(input: &str) -> Result<Self> {
        let mut mods = Modifiers::empty();
        let mut code: Option<Code> = None;

        for raw in input.split('+') {
            let token = raw.trim();
            if token.is_empty() {
                return Err(Error::InvalidRequest(format!(
                    "hotkey \"{input}\" has an empty component; write it as \
                     Modifier+Modifier+Key, e.g. \"Cmd+Shift+4\""
                )));
            }

            if let Some(modifier) = parse_modifier(token) {
                mods |= modifier;
                continue;
            }

            let parsed = parse_code(token).ok_or_else(|| {
                Error::InvalidRequest(format!(
                    "hotkey \"{input}\" names an unrecognised key \"{token}\""
                ))
            })?;

            if code.replace(parsed).is_some() {
                return Err(Error::InvalidRequest(format!(
                    "hotkey \"{input}\" names more than one non-modifier key; \
                     exactly one is required"
                )));
            }
        }

        let code = code.ok_or_else(|| {
            Error::InvalidRequest(format!(
                "hotkey \"{input}\" is only modifiers; it must also name a key, \
                 e.g. \"Cmd+Shift+4\""
            ))
        })?;

        Ok(Self { mods, code })
    }

    /// The keysym name a Wayland compositor's config file expects.
    ///
    /// `None` for keys with no stable X11 keysym spelling, which is the signal
    /// that no config line can be generated for this combination.
    #[must_use]
    pub fn keysym(&self) -> Option<&'static str> {
        keysym_for(self.code)
    }

    /// Whether this is a combination the OS commonly owns by default.
    ///
    /// This is advisory metadata, not proof of a current conflict.
    #[must_use]
    pub fn system_owner(&self) -> Option<&'static ReservedShortcut> {
        reserved_shortcuts()
            .iter()
            .find(|reserved| Self::parse(reserved.accelerator).is_ok_and(|it| it == *self))
    }

    /// The combination in the platform's own notation, for a menu or a label.
    ///
    /// macOS prints modifiers as glyphs and never separates them, so
    /// `Cmd+Shift+8` belongs on a menu item as `⇧⌘8`. Writing "Cmd+Shift+8"
    /// there is immediately recognisable as not-a-Mac-app. Everywhere else the
    /// spelled form *is* the platform idiom, so this is [`Display`](fmt::Display)
    /// verbatim.
    ///
    /// The glyph order is Apple's — control, option, shift, command — and is not
    /// the order [`Display`](fmt::Display) happens to use by coincidence: both
    /// follow the same table because it is the same convention.
    #[must_use]
    pub fn symbols(&self) -> String {
        if !cfg!(target_os = "macos") {
            return self.to_string();
        }
        let mut out = String::new();
        if self.mods.contains(Modifiers::CONTROL) {
            out.push('\u{2303}');
        }
        if self.mods.contains(Modifiers::ALT) {
            out.push('\u{2325}');
        }
        if self.mods.contains(Modifiers::SHIFT) {
            out.push('\u{21e7}');
        }
        if self.mods.contains(Modifiers::SUPER) {
            out.push('\u{2318}');
        }
        out.push_str(&display_for(self.code));
        out
    }

    fn to_hotkey(self) -> HotKey {
        HotKey::new(Some(self.mods), self.code)
    }

    fn id(self) -> u32 {
        self.to_hotkey().id()
    }
}

impl fmt::Display for Accelerator {
    /// Renders in the platform's own idiom: `Ctrl+Alt+Shift+Cmd+Key` order on
    /// macOS, which is the order Apple prints them in, and the same order with
    /// `Win` in place of `Cmd` elsewhere.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.mods.contains(Modifiers::CONTROL) {
            write!(f, "Ctrl+")?;
        }
        if self.mods.contains(Modifiers::ALT) {
            write!(
                f,
                "{}+",
                if cfg!(target_os = "macos") {
                    "Opt"
                } else {
                    "Alt"
                }
            )?;
        }
        if self.mods.contains(Modifiers::SHIFT) {
            write!(f, "Shift+")?;
        }
        if self.mods.contains(Modifiers::SUPER) {
            write!(
                f,
                "{}+",
                if cfg!(target_os = "macos") {
                    "Cmd"
                } else {
                    "Win"
                }
            )?;
        }
        write!(f, "{}", display_for(self.code))
    }
}

/// The modifier that `Cmd`, `Command`, `Super` and `Meta` all name here.
const PRIMARY: Modifiers = if cfg!(target_os = "macos") {
    Modifiers::SUPER
} else {
    Modifiers::CONTROL
};

fn parse_modifier(token: &str) -> Option<Modifiers> {
    match token.to_ascii_uppercase().as_str() {
        // Interchangeable spellings of the primary modifier. `Cmd` maps to
        // Control off macOS, which is what a cross-platform default means.
        "CMD" | "COMMAND" | "SUPER" | "META" | "CMDORCTRL" | "CMDORCONTROL" | "COMMANDORCTRL"
        | "COMMANDORCONTROL" => Some(PRIMARY),
        "CTRL" | "CONTROL" => Some(Modifiers::CONTROL),
        "ALT" | "OPT" | "OPTION" => Some(Modifiers::ALT),
        "SHIFT" => Some(Modifiers::SHIFT),
        // The escape hatch: the physical Super/Windows key, unmapped.
        "WIN" | "WINDOWS" | "LOGO" | "HYPER" => Some(Modifiers::SUPER),
        _ => None,
    }
}

